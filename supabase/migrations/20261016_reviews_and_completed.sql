-- Avaliações publicadas por clientes após atendimentos concluídos.
ALTER TABLE public.bookings DROP CONSTRAINT IF EXISTS bookings_status_check;
ALTER TABLE public.bookings ADD CONSTRAINT bookings_status_check CHECK (status IN ('pendente','confirmado','concluido','cancelado'));

CREATE TABLE IF NOT EXISTS public.reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL UNIQUE REFERENCES public.bookings(id) ON DELETE CASCADE,
  client_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  provider_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment varchar(500) NOT NULL DEFAULT '',
  created timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS reviews_provider_idx ON public.reviews(provider_id, created DESC);
CREATE INDEX IF NOT EXISTS reviews_client_idx ON public.reviews(client_id, created DESC);
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
